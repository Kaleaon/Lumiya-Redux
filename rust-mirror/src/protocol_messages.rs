#[cfg(test)]
mod tests {
    use super::{descriptor, MIGRATED_MESSAGES};
    use std::collections::HashSet;

    #[test]
    fn migrated_registry_is_complete_and_unique() {
        assert_eq!(MIGRATED_MESSAGES.len(), 461);
        let names: HashSet<_> = MIGRATED_MESSAGES
            .iter()
            .map(|message| message.name)
            .collect();
        assert_eq!(names.len(), MIGRATED_MESSAGES.len());
    }

    #[test]
    fn descriptor_preserves_wire_metadata() {
        let close = descriptor("CloseCircuit").expect("CloseCircuit descriptor");
        assert_eq!(
            close.template,
            "CloseCircuit Fixed 0xFFFFFFFD NotTrusted Unencoded"
        );
        assert!(!close.zero_coded);
        assert_eq!(close.fixed_payload_size, Some(4));
        assert_eq!(close.handler, "HandleCloseCircuit");
    }
}
